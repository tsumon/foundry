import inspectionGoldens from "./test/repositoryInspectionGoldens.json";
it.each(inspectionGoldens.map((r, i) => ({ r, i })))(
  "preserves backend-authored canonical receipt $i including null/escaping",
  async ({ r }) => {
    vi.stubGlobal("crypto", testCrypto);
    // JSON object order is not part of the transport contract.
    const reverseFields = (v: unknown): unknown =>
      Array.isArray(v)
        ? v.map(reverseFields)
        : v && typeof v === "object"
          ? Object.fromEntries(
              Object.entries(v)
                .reverse()
                .map(([k, x]) => [k, reverseFields(x)]),
            )
          : v;
    const reordered = reverseFields(r);
    vi.stubGlobal(
      "fetch",
      vi.fn(async () => response(reordered)),
    );
    expect(
      await repositoryImportApi.inspect({
        repo_path: r.root,
        consent: true,
        spec: r.spec as never,
      }),
    ).toEqual(r);
  },
);
